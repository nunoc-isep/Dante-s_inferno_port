"""Differential test of the SPU recompiler (tools/spu_recomp.py) against the SPU interpreter.

Random straight-line programs (ALU / float / load / store ops plus forward conditional branches)
are translated with the real emitter, then each one runs twice from the same initial state: once
interpreted only and once through the recompiled code. All 128 registers, a data area of local
store and the exit status must match.

Usage (from dante-port/): python -I tests/spu_recomp_test.py [--seed N] [--programs N]
"""
import os
import random
import struct
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import spu_recomp  # noqa: E402
from spu_isa import OPS, BITS  # noqa: E402

BASE = 0x100          # program load address in LS
DATA = 0x30000        # r1 points here; stqd only stores relative to r1
EXCLUDE = {
    # control flow / system (branches other than the forward conditional ones are not generated)
    "br", "bra", "brsl", "brasl", "bi", "bisl", "bisled", "biz", "binz", "bihz", "bihnz", "iret",
    "hbr", "hbra", "hbrr", "stop", "stopd", "sync", "dsync", "rdch", "wrch", "rchcnt",
    "heq", "heqi", "hgt", "hgti", "hlgt", "hlgti", "mfspr", "mtspr", "fscrrd", "fscrwr",
    # stores to computed addresses could overwrite the program itself
    "stqx", "stqa", "stqr",
}
COND_BRANCHES = {"brz", "brnz", "brhz", "brhnz"}


def enc(name, fmt, opc, rnd):
    w = (opc << (32 - BITS[fmt])) | rnd.getrandbits(32 - BITS[fmt])
    if fmt == "RRR":
        if (w >> 21) & 0x7F == 1:
            w ^= 2 << 21  # never write r1 (the store base)
    elif (w & 0x7F) == 1:
        w ^= 2  # never write r1
    if name == "stqd":
        w = (w & ~(0x7F << 7)) | (1 << 7)  # ra = r1
    return w


def gen_program(rnd, n):
    ops = [(nm, f, o) for nm, f, o in OPS if nm not in EXCLUDE and nm not in COND_BRANCHES]
    words = []
    # br +8 enters the recompiled code at a label (a taken branch); the skipped word is filler
    br = [o for nm, f, o in OPS if nm == "br"][0]
    words.append((br << 23) | ((2 & 0xFFFF) << 7))
    words.append(0x40200000)  # nop
    for k in range(n):
        if rnd.random() < 0.08:
            nm, f, o = rnd.choice([x for x in OPS if x[0] in COND_BRANCHES])
            fwd = rnd.randint(1, max(1, n - k))  # forward, at most to the final stop
            w = (o << 23) | ((fwd & 0xFFFF) << 7) | rnd.randrange(128)
        else:
            nm, f, o = rnd.choice(ops)
            w = enc(nm, f, o, rnd)
        words.append(w)
    stop = [o for nm, f, o in OPS if nm == "stop"][0]
    words.append((stop << 21) | 0x102)
    return words


def main():
    seed = int(sys.argv[sys.argv.index("--seed") + 1]) if "--seed" in sys.argv else 1
    nprog = int(sys.argv[sys.argv.index("--programs") + 1]) if "--programs" in sys.argv else 40
    rnd = random.Random(seed)
    progs = [gen_program(rnd, rnd.randint(20, 80)) for _ in range(nprog)]

    gen = ["// generated by tests/spu_recomp_test.py", '#include "spu/spu_ops.h"', '#include "spu/spu_native.h"', ""]
    descs = []
    for i, words in enumerate(progs):
        ls = bytearray(0x40000)
        for k, w in enumerate(words):
            struct.pack_into(">I", ls, BASE + 4 * k, w)
        lo, hi = BASE, BASE + 4 * len(words)
        code, labels = spu_recomp.discover(bytes(ls), BASE, [(lo, hi)], raw=True)
        desc, _, _ = spu_recomp.emit_image(i, f"t{i}", BASE, bytes(ls), lo, hi, code, labels, gen)
        descs.append(desc)
    gen.append("const SpuImageDesc g_spu_images[] = {")
    gen += descs
    gen.append("};")
    gen.append(f"const uint32_t g_spu_image_count = {len(descs)};")

    h = ['#include <cstdio>', '#include <cstring>', '#include <memory>', '#include "spu/spu.h"', '#include "spu/spu_native.h"', "",
         "static void setup(SpuThread& t, const uint32_t* prog, int n, unsigned seed) {",
         "\tmemset(t.ls, 0, 0x40000);",
         "\tfor (int k = 0; k < n; ++k) ppc_st32(t.ls + 0x100 + 4 * k, prog[k]);",
         "\tunsigned x = seed * 2654435761u + 1;",
         "\tfor (int r = 0; r < 128; ++r) for (int i = 0; i < 4; ++i) { x = x * 1103515245u + 12345u; VW(t.gpr[r], i) = x ^ (x >> 16); }",
         "\tfor (int a = 0x30000 - 0x2000; a < 0x30000 + 0x2000; a += 4) { x = x * 1103515245u + 12345u; ppc_st32(t.ls + a, x); }",
         f"\tVW(t.gpr[1], 0) = 0x{DATA:X};",
         "\tt.pc = 0x100;",
         "\tspu_native_ls_written(t, 0, 0x40000);",
         "}", "", "int main() {", "\tvm::init();", "\tint fails = 0;"]
    for i, words in enumerate(progs):
        h.append(f"\t{{ static const uint32_t p[] = {{{','.join(f'0x{w:08X}u' for w in words)}}};")
        h.append("\t  auto a = std::make_unique<SpuThread>(), b = std::make_unique<SpuThread>();")
        h.append(f"\t  setup(*a, p, {len(words)}, {i}); setup(*b, p, {len(words)}, {i});")
        h.append("\t  spu_native_set_enabled(false); spu_run(*a);")
        h.append("\t  spu_native_set_enabled(true); spu_run(*b);")
        h.append("\t  bool ok = a->exit_status == b->exit_status && b->native_calls > 0;")
        h.append("\t  int bad = -1; for (int r = 0; r < 128 && ok; ++r) if (memcmp(&a->gpr[r], &b->gpr[r], 16)) { ok = false; bad = r; }")
        h.append("\t  if (ok && memcmp(a->ls + 0x2E000, b->ls + 0x2E000, 0x4000)) { ok = false; bad = 1000; }")
        h.append(f"\t  if (!ok) {{ ++fails; printf(\"FAIL program {i}: status %u/%u native_calls %llu, first difference %d\\n\", "
                 "a->exit_status, b->exit_status, (unsigned long long)b->native_calls, bad); } }")
    h += [f'\tprintf("%d/%d recompiler programs match the interpreter\\n", {nprog} - fails, {nprog});', "\treturn fails != 0;", "}"]

    build = os.path.join(ROOT, "build")
    os.makedirs(build, exist_ok=True)
    gsrc, hsrc = os.path.join(build, "spu_recomp_test_images.cpp"), os.path.join(build, "spu_recomp_test.cpp")
    open(gsrc, "w").write("\n".join(gen) + "\n")
    open(hsrc, "w").write("\n".join(h) + "\n")
    stub = os.path.join(build, "spu_recomp_test_stubs.cpp")
    open(stub, "w").write('#include "kernel/kernel.h"\n'
                          "uint64_t ppc_mftb() { return 0; }\n"
                          "GuestThread* current_thread() { return nullptr; }\n"
                          "uint32_t thread_id(GuestThread*) { return 0; }\n"
                          "int thread_join(uint32_t, uint64_t*) { return 0; }\n"
                          "int thread_detach(uint32_t) { return 0; }\n"
                          "void thread_exit(uint64_t) { throw 0; }\n"
                          "void syscall_register(uint32_t, const char*, SyscallFn) {}\n"
                          '#include "spu/spu.h"\n'
                          "bool g_spu_profile = false;\n"
                          "void spu_note_overlay(SpuThread&, uint32_t, uint32_t, uint32_t) {}\n"
                          "void spu_note_overlay_exec(void*) {}\n"
                          "void host_sleep_us(uint64_t) {}\n")
    rt = os.path.join(ROOT, "runtime")
    srcs = [hsrc, gsrc, stub] + [os.path.join(rt, *p) for p in (("spu", "spu_interp.cpp"), ("spu", "spu_channels.cpp"),
                                                               ("kernel", "memory.cpp"), ("kernel", "sync.cpp"),
                                                               ("kernel", "reservation.cpp"), ("spu", "spu_native.cpp"))]
    exe = os.path.join(build, "spu_recomp_test.exe")
    subprocess.check_call(["clang++", "-std=c++20", "-march=x86-64-v3", "-O2", "-w", "-I", rt, "-I", build, *srcs, "-o", exe,
                           "-static", "-Wl,--whole-archive", "-lpthread", "-Wl,--no-whole-archive", "-lsynchronization"])
    return subprocess.call([exe])


if __name__ == "__main__":
    sys.exit(main())
